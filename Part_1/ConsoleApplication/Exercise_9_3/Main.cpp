//Напишите функцию reverse, которая принимает на вход массив произвольного размера и «разворачивает» его в обратную сторону — то есть первый элемент становится последним и наоборот.Выведите на консоль массив до вызова функции и после вызова функции.
//
//Обратите внимание, что функция reverse должна изменять передаваемый ей массив.Элементы в нём должны изменить свой порядок.
//
//Пример работы программы
//До функции reverse : 1 2 3 4 5 6 7 8 9
//После функции reverse : 9 8 7 6 5 4 3 2 1

#include <iostream>

// Функция для вывода массива
void print(const int* arr, int size) {
    for (int i = 0; i < size; ++i) {
        std::cout << arr[i] << " ";
    }
    std::cout << std::endl;
}

// Функция для обмена двух элементов (из задачи 2)
void swap(int* a, int* b) {
    int temp = *a;
    *a = *b;
    *b = temp;
}

// Функция переворота массива с использованием указателей
void reverse(int* arr, int size) {
    int* left = arr;           // Указатель на первый элемент
    int* right = arr + size - 1; // Указатель на последний элемент

    // Меняем элементы, пока указатели не встретятся
    while (left < right) {
        swap(left, right);  // Меняем местами элементы
        left++;   // Двигаем левый указатель вправо
        right--;  // Двигаем правый указатель влево
    }
}

int main() {
    // Создаём массив
    int arr[] = { 1, 2, 3, 4, 5, 6, 7, 8, 9 };
    int size = sizeof(arr) / sizeof(arr[0]);

    // Выводим массив до переворота
    std::cout << "До функции reverse: ";
    print(arr, size);

    // Переворачиваем массив
    reverse(arr, size);

    // Выводим массив после переворота
    std::cout << "После функции reverse: ";
    print(arr, size);

    return 0;
}