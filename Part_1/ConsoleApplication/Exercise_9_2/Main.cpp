#include <iostream>

// Функция swap с использованием указателей
void swap(int* a, int* b) {
    int temp = *a;  // Сохраняем значение по адресу a
    *a = *b;        // Записываем значение по адресу b в a
    *b = temp;      // Записываем сохранённое значение в b
}

int main() {
    int a = 5, b = 8;

    // Выводим исходные значения
    std::cout << "a = " << a << ", b = " << b << std::endl;

    // Вызываем swap, передавая адреса переменных
    swap(&a, &b);

    // Выводим значения после обмена
    std::cout << "a = " << a << ", b = " << b << std::endl;

    return 0;
}