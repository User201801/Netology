#include <iostream>

// Функция создания массива
double* create_array(int size) {
    // Выделяем динамическую память под массив типа double
    double* arr = new double[size];

    // Инициализируем все элементы нулями
    for (int i = 0; i < size; ++i) {
        arr[i] = 0.0;  // или arr[i] = 0;
    }

    // Возвращаем указатель на созданный массив
    return arr;
}

int main() {
    setlocale(LC_ALL, "Russian");
    int size;

    // Запрашиваем размер массива
    std::cout << "Введите размер массива: ";
    std::cin >> size;

    // Создаём массив с помощью функции
    double* arr = create_array(size);

    // Выводим массив
    std::cout << "Массив: ";
    for (int i = 0; i < size; ++i) {
        std::cout << arr[i] << " ";
    }
    std::cout << std::endl;

    // Очищаем память
    delete[] arr;

    return 0;
}